// Generates TypeScript types from schemas/** into src/shared/storage/generated/ (T034).
// Runs as the prebuild and pretest hooks, so the types never drift from the schemas.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { SCHEMA_NAMES } from '../src/shared/storage/schemas.ts';

const root = resolve(import.meta.dirname, '..');
const schemaDir = join(root, 'schemas');
const outDir = join(root, 'src/shared/storage/generated');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const banner = '/* Generated by scripts/gen-types.ts from schemas/. Do not edit; run `npm run gen-types`. */';
const index: string[] = [banner];

for (const name of SCHEMA_NAMES) {
  const file = join(schemaDir, `${name}.schema.json`);
  const schema = JSON.parse(readFileSync(file, 'utf8'));
  // Resolve ../defs.schema.json refs from disk rather than fetching the https $id.
  delete schema.$id;
  const ts = await compile(schema, schema.title, {
    cwd: dirname(file),
    bannerComment: banner,
    additionalProperties: false,
    format: true,
    strictIndexSignatures: true,
    unreachableDefinitions: false,
  });
  const out = `${name.replace('/', '-')}.ts`;
  writeFileSync(join(outDir, out), ts);
  index.push(`export type * from './${out}';`);
}

writeFileSync(join(outDir, 'index.ts'), `${index.join('\n')}\n`);
console.log(`gen-types: ${SCHEMA_NAMES.length} schemas -> ${outDir}`);
